#!/usr/bin/perl
#
# Generate ucs2_upper.h, a table to convert UTF-16 code units of the
# Basic Multilingual Plane to upper case.
#
# NTLM uses upper case user names to compute password hashes.
# Windows uses Unicode simple case mapping (one character to one).
#
# To avoid requiring Unicode::UCD, which is not available in some Perl
# installations (like the one in Git for Windows), the mapping is
# computed using Perl builtin uc(): if uc() returns more characters
# (full case mapping, like German sharp s to "SS") ucfirst() is used,
# the title case is a single character for Greek letters with iota
# subscript, matching the simple mapping. If Unicode::UCD is available
# the result is checked against Simple_Uppercase_Mapping.
#
# The table is a sorted list of ranges; in a range every character
# starting from the first is converted adding delta (modulo 65536).
# As an exception, if delta is 0xffff (that is -1, like many Latin
# letters where lower case follows upper case) only every other
# character is converted. This saves a field in the table.

use strict;
use warnings;

# compute upper case of each BMP character
my @upper = (0 .. 0xffff);
for my $c (0 .. 0xffff) {
	next if $c >= 0xd800 && $c < 0xe000;
	my $s = chr($c);
	# force Unicode semantic for characters < 256
	utf8::upgrade($s);
	my $u = uc($s);
	$u = ucfirst($s) if length($u) != 1;
	$upper[$c] = ord($u) if length($u) == 1 && ord($u) <= 0xffff;
}

check_with_ucd() if eval { require Unicode::UCD; 1 };

# Check computed mapping against Unicode::UCD simple mapping
sub check_with_ucd
{
	my ($list, $map, $format) = Unicode::UCD::prop_invmap('Simple_Uppercase_Mapping');
	die "unexpected format $format\n" unless $format eq 'a';

	my @ucd = (0 .. 0xffff);
	for my $i (0 .. $#$list) {
		my $start = $list->[$i];
		last if $start > 0xffff;
		my $end = $i < $#$list ? $list->[$i + 1] - 1 : 0x10ffff;
		$end = 0xffff if $end > 0xffff;
		my $value = $map->[$i];
		next if ref($value) || $value == 0;
		for my $c ($start .. $end) {
			my $u = $value + ($c - $start);
			$ucd[$c] = $u if $u <= 0xffff;
		}
	}
	for my $c (0 .. 0xffff) {
		next if $c >= 0xd800 && $c < 0xe000;
		die sprintf("upper case of U+%04X differs: uc() gives U+%04X, Unicode::UCD U+%04X\n", $c, $upper[$c], $ucd[$c])
			if $upper[$c] != $ucd[$c];
	}
}

# collect mappings, skipping surrogates
my @pairs;
for my $c (0 .. 0xffff) {
	next if $c >= 0xd800 && $c < 0xe000;
	push @pairs, [$c, $upper[$c]] if $upper[$c] != $c;
}

# compress in ranges
my @ranges;
my $i = 0;
while ($i < @pairs) {
	my ($c, $u) = @{$pairs[$i]};
	my $delta = $u - $c;
	my ($best_len, $best_step) = (1, 1);
	# use step 2 only for delta -1, see above
	for my $step ($delta == -1 ? (2) : (1)) {
		my $j = $i;
		while ($j + 1 < @pairs && $pairs[$j + 1][0] == $pairs[$j][0] + $step
		       && $pairs[$j + 1][1] - $pairs[$j + 1][0] == $delta) {
			++$j;
		}
		($best_len, $best_step) = ($j - $i + 1, $step) if $j - $i + 1 > $best_len;
	}
	push @ranges, [$c, $pairs[$i + $best_len - 1][0], $delta & 0xffff];
	$i += $best_len;
}

print <<"EOF";
/*
 * This file is generated by ucs2_upper.pl.
 * Do not edit, edit the generator instead.
 */

typedef struct
{
	uint16_t first, last, delta;
} ucs2_upper_range;

static const ucs2_upper_range ucs2_upper_ranges[] = {
EOF
for my $r (@ranges) {
	printf "\t{ 0x%04x, 0x%04x, 0x%04x },\n", @$r;
}
print "};\n";
